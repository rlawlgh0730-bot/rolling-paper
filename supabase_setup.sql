-- 1. 메모를 저장할 'rolling_papers' 테이블 만들기
CREATE TABLE IF NOT EXISTS public.rolling_papers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname TEXT NOT NULL,
    content TEXT NOT NULL,
    color TEXT NOT NULL DEFAULT 'yellow',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. 보안 설정(RLS: Row Level Security) 켜기
ALTER TABLE public.rolling_papers ENABLE ROW LEVEL SECURITY;

-- 3. 사이트에 접속한 '누구나' 메모를 읽을 수 있도록 허용 (SELECT 정책)
CREATE POLICY "누구나 메모를 볼 수 있음"
ON public.rolling_papers
FOR SELECT
TO anon, authenticated
USING (true);

-- 4. 사이트에 접속한 '누구나' 새 메모를 작성할 수 있도록 허용 (INSERT 정책)
CREATE POLICY "누구나 메모를 작성할 수 있음"
ON public.rolling_papers
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

